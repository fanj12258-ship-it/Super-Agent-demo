function listFor(key) {
  var base = (CATALOG[key] || []).slice();
  if (key === 'scenario' && scenes.length) {
    scenes.forEach(function (sc) {
      var kids = (sc.businesses || []).filter(function (b) { return b.name; }).map(function (b) {
        return {
          name: b.name,
          desc: b.desc || 'No description yet',
          priority: b.priority || 'Quick win',
          stage: 'not_started'
        };
      });
      base.unshift({
        name: sc.title,
        desc: sc.desc || sc.appDesc || 'No description yet',
        stage: 'not_started',
        isNew: true,
        assets: [
          { type: 'Ontology', label: 'Not linked', state: 'is-empty' },
          { type: 'Skill', label: 'Not linked', state: 'is-empty' },
          { type: 'Knowledge', label: 'Not linked', state: 'is-empty' }
        ],
        businesses: kids
      });
    });
  }
  if (key === 'agent' && importedAgents.length) {
    importedAgents.forEach(function (ag) {
      base.unshift({
        name: ag.name,
        role: ag.role,
        model: ag.model,
        caps: ag.caps.slice(),
        status: ag.status,
        state: ag.state,
        runs: ag.runs,
        color: ag.color,
        letter: ag.letter,
        isNew: true
      });
    });
  }
  return base;
}
